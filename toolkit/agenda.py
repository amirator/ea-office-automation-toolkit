"""Turn a meeting brief + chosen slot into a timed agenda (Markdown, DOCX, optional PDF) and .ics invite."""

from __future__ import annotations

import json
import shutil
import subprocess
from dataclasses import dataclass
from datetime import datetime, timedelta
from pathlib import Path

from docx import Document
from docx.enum.table import WD_TABLE_ALIGNMENT
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from docx.shared import Cm, Pt, RGBColor

from toolkit.common import GREY, NAVY, SAMPLE_BANNER, TEAL, ensure_dir
from toolkit.ics import write_invite
from toolkit.scheduler import Attendee, Slot


@dataclass
class AgendaItem:
    number: int
    start: datetime
    end: datetime
    topic: str
    owner: str
    kind: str
    minutes: int
    pre_read: str = ""


def load_brief(path: str | Path) -> dict:
    brief = json.loads(Path(path).read_text(encoding="utf-8"))
    if not brief.get("items"):
        raise ValueError("Meeting brief must contain at least one agenda item")
    return brief


def build_items(brief: dict, start: datetime) -> list[AgendaItem]:
    items, t = [], start
    for i, it in enumerate(brief["items"], 1):
        end = t + timedelta(minutes=int(it["minutes"]))
        items.append(AgendaItem(i, t, end, it["topic"], it["owner"], it.get("type", "Discussion"),
                                int(it["minutes"]), it.get("pre_read", "")))
        t = end
    return items


def _fmt_slot(s: Slot) -> str:
    return f"{s.start:%a %d %b %Y, %H:%M}-{s.end:%H:%M} (Asia/Riyadh)"


def render_markdown(brief, slot: Slot, items, attendees: list[Attendee], alternatives: list[Slot],
                    sample: bool) -> str:
    lines = []
    if sample:
        lines += [f"> **{SAMPLE_BANNER}**", ""]
    lines += [f"# {brief['title']}", "",
              f"**When:** {_fmt_slot(slot)}  ",
              f"**Where:** {brief.get('location', '')}  ",
              f"**Chair:** {brief.get('chair', '')}  ",
              f"**Organiser:** {brief.get('organiser', '')}", "",
              f"**Purpose:** {brief.get('purpose', '')}", "",
              "## Attendees and local times", "", "| Attendee | Role | Local time |", "|---|---|---|"]
    lines += [f"| {p.name} | {p.role} | {slot.local_times[p.name]} |" for p in attendees]
    lines += ["", "## Agenda", "", "| # | Time (Riyadh) | Item | Owner | Type | Min |", "|---|---|---|---|---|---|"]
    lines += [f"| {i.number} | {i.start:%H:%M}-{i.end:%H:%M} | {i.topic} | {i.owner} | {i.kind} | {i.minutes} |"
              for i in items]
    pre = [i for i in items if i.pre_read]
    if pre:
        lines += ["", "## Pre-reads (circulate 48 hours before)", ""]
        lines += [f"- Item {i.number}: {i.pre_read} ({i.owner})" for i in pre]
    alts = [a for a in alternatives if a.start != slot.start]
    if alts:
        lines += ["", "## Alternative slots (all attendees free)", ""]
        lines += [f"- {_fmt_slot(a)}" for a in alts]
    if slot.notes:
        lines += ["", f"_Scheduling note: {'; '.join(slot.notes)}._"]
    lines += ["", "---", "_Generated by EA Office Automation Toolkit._", ""]
    return "\n".join(lines)


def _shade(cell, hex_colour: str) -> None:
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), hex_colour)
    tcPr.append(shd)


def _table(doc, header, rows, widths, zebra="F4F6F8"):
    t = doc.add_table(rows=1, cols=len(header))
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.style = "Table Grid"
    for c, h in zip(t.rows[0].cells, header):
        c.text = ""
        run = c.paragraphs[0].add_run(h)
        run.bold, run.font.size = True, Pt(9.5)
        run.font.color.rgb = RGBColor(0xFF, 0xFF, 0xFF)
        _shade(c, NAVY)
    for n, row in enumerate(rows):
        cells = t.add_row().cells
        for c, v in zip(cells, row):
            c.text = ""
            run = c.paragraphs[0].add_run(str(v))
            run.font.size = Pt(9.5)
            if n % 2:
                _shade(c, zebra)
    _set_widths(t, widths)
    return t


def _set_widths(t, widths) -> None:
    """Fixed column widths that Word *and* LibreOffice respect (grid + every cell)."""
    t.autofit = False
    grid = t._tbl.tblGrid
    for gc, w in zip(grid.findall(qn("w:gridCol")), widths):
        gc.set(qn("w:w"), str(int(Cm(w).twips)))
    for row in t.rows:
        for c, w in zip(row.cells, widths):
            c.width = Cm(w)


def render_docx(path, brief, slot: Slot, items, attendees, alternatives, sample: bool) -> Path:
    doc = Document()
    sec = doc.sections[0]
    sec.page_height, sec.page_width = Cm(29.7), Cm(21.0)
    sec.left_margin = sec.right_margin = Cm(1.8)
    sec.top_margin = sec.bottom_margin = Cm(1.5)
    style = doc.styles["Normal"]
    style.font.name, style.font.size = "Calibri", Pt(10.5)

    if sample:
        p = doc.add_paragraph()
        r = p.add_run(SAMPLE_BANNER.upper())
        r.bold, r.font.size = True, Pt(8)
        r.font.color.rgb = RGBColor.from_string("D64545")
        p.alignment = WD_ALIGN_PARAGRAPH.RIGHT

    p = doc.add_paragraph()
    r = p.add_run(brief["title"])
    r.bold, r.font.size = True, Pt(20)
    r.font.color.rgb = RGBColor.from_string(NAVY)
    p = doc.add_paragraph()
    r = p.add_run(f"Meeting agenda  |  {_fmt_slot(slot)}")
    r.font.size, r.font.color.rgb = Pt(11), RGBColor.from_string(TEAL)

    meta = [("Location", brief.get("location", "")), ("Chair", brief.get("chair", "")),
            ("Organiser", brief.get("organiser", "")), ("Purpose", brief.get("purpose", ""))]
    t = doc.add_table(rows=0, cols=2)
    for k, v in meta:
        cells = t.add_row().cells
        cells[0].text, cells[1].text = "", ""
        rk = cells[0].paragraphs[0].add_run(k)
        rk.bold, rk.font.size = True, Pt(9.5)
        rk.font.color.rgb = RGBColor.from_string(GREY)
        cells[1].paragraphs[0].add_run(v).font.size = Pt(9.5)
    _set_widths(t, [3.0, 14.4])

    def heading(text):
        hp = doc.add_paragraph()
        hp.paragraph_format.space_before = Pt(12)
        hr = hp.add_run(text)
        hr.bold, hr.font.size = True, Pt(12.5)
        hr.font.color.rgb = RGBColor.from_string(NAVY)

    heading("Agenda")
    _table(doc, ["#", "Time", "Item", "Owner", "Type", "Min"],
           [[i.number, f"{i.start:%H:%M}-{i.end:%H:%M}", i.topic, i.owner, i.kind, i.minutes] for i in items],
           [0.8, 2.3, 7.4, 3.2, 2.3, 1.2])
    total = sum(i.minutes for i in items)
    p = doc.add_paragraph()
    r = p.add_run(f"Total {total} minutes of a {int((slot.end - slot.start).total_seconds() // 60)}-minute slot "
                  f"(remaining time held as buffer). Times shown in Asia/Riyadh.")
    r.italic, r.font.size = True, Pt(8.5)
    r.font.color.rgb = RGBColor.from_string(GREY)

    heading("Attendees and local times")
    _table(doc, ["Attendee", "Role", "Local time"],
           [[a.name, a.role, slot.local_times[a.name]] for a in attendees], [4.2, 5.4, 7.6])

    pre = [i for i in items if i.pre_read]
    if pre:
        heading("Pre-reads (circulate 48 hours before)")
        for i in pre:
            doc.add_paragraph(f"Item {i.number}: {i.pre_read} ({i.owner})", style="List Bullet")
    alts = [a for a in alternatives if a.start != slot.start]
    if alts:
        heading("Alternative slots (all attendees free)")
        for a in alts:
            doc.add_paragraph(_fmt_slot(a), style="List Bullet")
    if slot.notes:
        p = doc.add_paragraph()
        r = p.add_run("Scheduling note: " + "; ".join(slot.notes) + ".")
        r.italic, r.font.size = True, Pt(9)
    footer = sec.footer.paragraphs[0]
    footer.text = "Generated by EA Office Automation Toolkit"
    footer.runs[0].font.size, footer.runs[0].font.color.rgb = Pt(8), RGBColor.from_string(GREY)
    out = Path(path)
    doc.save(out)
    return out


def docx_to_pdf(docx_path: Path) -> Path | None:
    """Convert with LibreOffice if it is installed; returns None otherwise (DOCX is still produced)."""
    exe = shutil.which("soffice") or shutil.which("libreoffice")
    if not exe:
        return None
    subprocess.run([exe, "--headless", "--convert-to", "pdf", "--outdir", str(docx_path.parent), str(docx_path)],
                   check=True, capture_output=True, timeout=120)
    pdf = docx_path.with_suffix(".pdf")
    return pdf if pdf.exists() else None


def generate_agenda(brief_path, slot: Slot, attendees, alternatives, out_dir, sample=True, pdf=False) -> dict:
    brief = load_brief(brief_path)
    items = build_items(brief, slot.start)
    if items[-1].end > slot.end:
        raise ValueError(f"Agenda runs {sum(i.minutes for i in items)} min but the slot is shorter")
    out = ensure_dir(out_dir)
    stem = "agenda_" + slot.start.strftime("%Y%m%d_%H%M")
    md = out / f"{stem}.md"
    md.write_text(render_markdown(brief, slot, items, attendees, alternatives, sample), encoding="utf-8")
    docx = render_docx(out / f"{stem}.docx", brief, slot, items, attendees, alternatives, sample)
    invite = write_invite(out / f"{stem}.ics", brief["title"], slot.start, slot.end, brief.get("location", ""),
                          brief.get("purpose", ""), "executive.office@demo-holding.example",
                          [(a.name, a.email) for a in attendees])
    files = {"markdown": md, "docx": docx, "invite": invite}
    if pdf:
        p = docx_to_pdf(docx)
        if p:
            files["pdf"] = p
    return files
